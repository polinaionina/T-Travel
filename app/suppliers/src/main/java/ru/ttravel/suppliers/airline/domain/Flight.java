package ru.ttravel.suppliers.airline.domain;

import java.lang.annotation.Inherited;
import java.time.LocalDateTime;
import java.time.OffsetDateTime;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;

/**
 * A single scheduled departure of a flight in the airline simulator.
 * <p>
 * One row is one concrete departure: flight {@code SU123} on May 12 and
 * flight {@code SU123} on May 13 are two different rows. A flight is
 * identified by the pair {@code flightNo} + {@code scheduledDeparture}.
 * <p>
 * The flight holds no prices or seat counters: those depend on the fare
 * class and live in {@link FlightFare}.
 */
@Entity
@Table(name = "flight",
    uniqueConstraints = @UniqueConstraint(columnNames = {"flight_no", "scheduled_departure"}))
public class Flight {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id;

    /** Passenger-facing flight number, e.g. {@code SU123}. Not unique on its own: it repeats every day. */
    @Column(name = "flight_no", length = 6, nullable = false)
    private String flightNo;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "departure_airport", referencedColumnName = "code")
    private Airport departureAirport;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "arrival_airport", referencedColumnName = "code")
    private Airport arrivalAirport;

    /** Departure moment. Stored with an offset; the airport's local time is derived from {@link Airport#getTimezone()}. */
    @Column(name = "scheduled_departure", nullable = false)
    private OffsetDateTime scheduledDeparture;

    /** Arrival moment, in the same representation as {@link #scheduledDeparture}. */
    @Column(name = "scheduled_arrival", nullable = false)
    private OffsetDateTime scheduledArrival;

    /** Aircraft type operating the flight. Defines the total capacity. */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "aircraft_code", referencedColumnName = "code")
    private Aircraft aircraft;

    /** Flight state, e.g. {@code SCHEDULED} or {@code CANCELLED}. Search returns only {@code SCHEDULED} flights. */
    @Column(name = "status", nullable = false)
    private String status;

    /** Empty constructor, required by Hibernate. */
    protected Flight() {
    }

    /**
     * Creates a new flight. The id is generated by the database.
     *
     * @param flightNo           passenger-facing flight number
     * @param departureAirport   origin airport
     * @param arrivalAirport     destination airport
     * @param scheduledDeparture departure moment
     * @param scheduledArrival   arrival moment, must be after the departure
     * @param aircraft           aircraft type
     * @param status             initial status, usually {@code SCHEDULED}
     */
    public Flight(String flightNo, Airport departureAirport, Airport arrivalAirport,
                  OffsetDateTime scheduledDeparture, OffsetDateTime scheduledArrival,
                  Aircraft aircraft, String status) {
        this.flightNo = flightNo;
        this.departureAirport = departureAirport;
        this.arrivalAirport = arrivalAirport;
        this.scheduledDeparture = scheduledDeparture;
        this.scheduledArrival = scheduledArrival;
        this.aircraft = aircraft;
        this.status = status;
    }

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public String getFlightNo() {
        return flightNo;
    }

    public void setFlightNo(String flightNo) {
        this.flightNo = flightNo;
    }

    public Airport getDepartureAirport() {
        return departureAirport;
    }

    public void setDepartureAirport(Airport departureAirport) {
        this.departureAirport = departureAirport;
    }

    public Airport getArrivalAirport() {
        return arrivalAirport;
    }

    public void setArrivalAirport(Airport arrivalAirport) {
        this.arrivalAirport = arrivalAirport;
    }

    public OffsetDateTime getScheduledDeparture() {
        return scheduledDeparture;
    }

    public void setScheduledDeparture(OffsetDateTime scheduledDeparture) {
        this.scheduledDeparture = scheduledDeparture;
    }

    public OffsetDateTime getScheduledArrival() {
        return scheduledArrival;
    }

    public void setScheduledArrival(OffsetDateTime scheduledArrival) {
        this.scheduledArrival = scheduledArrival;
    }

    public Aircraft getAircraft() {
        return aircraft;
    }

    public void setAircraft(Aircraft aircraft) {
        this.aircraft = aircraft;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }
}