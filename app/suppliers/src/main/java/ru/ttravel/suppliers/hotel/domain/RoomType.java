package ru.ttravel.suppliers.hotel.domain;

import java.lang.annotation.Inherited;
import java.util.Map;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;

/**
 * A category of rooms in a {@link Hotel}, e.g. "Deluxe with sea view".
 * <p>
 * Guests book a room type, not a concrete room: rooms of one type are
 * interchangeable, so only the number of free rooms per night matters
 * (see {@link RoomAvailability}). The code is unique within a hotel.
 */
@Entity
@Table(name = "room_type",
        uniqueConstraints = @UniqueConstraint(columnNames = {"hotel_id", "code"})
)
public class RoomType {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "hotel_id", referencedColumnName = "id", nullable = false)
    private Hotel hotel;

    /** Short code of the type, e.g. {@code DELUXE}. Part of the public {@code offer_id}. Unique within a hotel. */
    @Column(name = "code", nullable = false)
    private String code;

    /** Display name of the room type. */
    @Column(name = "name", nullable = false)
    private String name;

    /** Maximum number of guests the room can hold. */
    @Column(name = "capacity", nullable = false)
    private Integer capacity;

    /** Base price per night. The generator derives per-night prices in {@link RoomAvailability} from it. */
    @Column(name = "base_price", nullable = true)
    private Long basePrice;

    /** Initial number of rooms of this type. Used by the generator; not read during booking. */
    @Column(name = "rooms_total", nullable = true)
    private Long roomTotal;

    /** Empty constructor, required by Hibernate. */
    protected RoomType() {}

    /**
     * Creates a new room type. The id is generated by the database.
     *
     * @param name      display name
     * @param code      short code, unique within the hotel
     * @param capacity  maximum number of guests
     * @param basePrice base price per night
     * @param roomTotal initial number of rooms of this type
     * @param hotel     hotel the type belongs to
     */
    public RoomType(String name, String code, Integer capacity, 
        Long basePrice, Long roomTotal, Hotel hotel) {
        this.name = name;
        this.code = code;
        this.capacity = capacity;
        this.basePrice = basePrice;
        this.roomTotal = roomTotal;
        this.hotel = hotel;
    }

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public Integer getCapacity() {
        return capacity;
    }

    public void setCapacity(Integer capacity) {
        this.capacity = capacity;
    }

    public Long getBasePrice() {
        return basePrice;
    }

    public void setBasePrice(Long basePrice) {
        this.basePrice = basePrice;
    }

    public Long getRoomTotal() {
        return roomTotal;
    }

    public void setRoomTotal(Long roomTotal) {
        this.roomTotal = roomTotal;
    }

    public Hotel getHotel() {
        return hotel;
    }

    public void setHotel(Hotel hotel) {
        this.hotel = hotel;
    }
    
}
