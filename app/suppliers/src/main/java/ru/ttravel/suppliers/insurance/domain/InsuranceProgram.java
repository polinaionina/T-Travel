package ru.ttravel.suppliers.insurance.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * An insurance program that can be sold, e.g. "Medical 50 000 EUR".
 * <p>
 * Unlike flights and hotels, insurance has no stock: any number of policies
 * can be issued. Rejections come from business rules (age limits, inactive
 * program, start date in the past) and from simulated faults.
 */
@Entity
@Table(name = "insurance_program")
public class InsuranceProgram {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id;

    @Column(name = "code", nullable = false, unique = true)
    private String code;

    @Column(name = "name", nullable = false)
    private String name;

    /** Where the program is valid: {@code RU}, {@code EUROPE} or {@code WORLD}. */
    @Column(name = "coverage_area", nullable = false)
    private String coverageArea;

    /** Insured sum in kopecks (minor currency units). For display only. */
    @Column(name = "coverage_amount", nullable = false)
    private Long coverageAmount;

    /** Base price per day per insured person, in kopecks. */
    @Column(name = "daily_rate", nullable = false)
    private Long dailyRate;

    @Column(name = "currency", length = 3, nullable = false)
    private String currency;

    @Column(name = "min_age", nullable = false)
    private Integer minAge;

    @Column(name = "max_age", nullable = false)
    private Integer maxAge;

    /** Extra coverage description as a JSON string (baggage, trip cancellation, sports). For display only. */
    @Column(name = "options", nullable = true, columnDefinition = "TEXT")
    private String options;

    /** {@code true} if the program is on sale. Inactive programs are not shown in search and cannot be booked. */
    @Column(name = "active", nullable = false)
    private Boolean active;

    /** Empty constructor, required by Hibernate. */
    protected InsuranceProgram() {
    }

    /**
     * Creates a new program. The id is generated by the database.
     *
     * @param code           unique short code
     * @param name           display name
     * @param coverageArea   coverage area code
     * @param coverageAmount insured sum in kopecks
     * @param dailyRate      base price per day per person in kopecks
     * @param currency       ISO 4217 currency code
     * @param minAge         minimum insured age
     * @param maxAge         maximum insured age
     * @param options        JSON description of extra coverage, may be {@code null}
     * @param active         whether the program is on sale
     */
    public InsuranceProgram(String code, String name, String coverageArea, Long coverageAmount,
                            Long dailyRate, String currency, Integer minAge, Integer maxAge,
                            String options, Boolean active) {
        this.code = code;
        this.name = name;
        this.coverageArea = coverageArea;
        this.coverageAmount = coverageAmount;
        this.dailyRate = dailyRate;
        this.currency = currency;
        this.minAge = minAge;
        this.maxAge = maxAge;
        this.options = options;
        this.active = active;
    }

    public Integer getId() { return id; }
    public void setId(Integer id) { this.id = id; }

    public String getCode() { return code; }
    public void setCode(String code) { this.code = code; }

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public String getCoverageArea() { return coverageArea; }
    public void setCoverageArea(String coverageArea) { this.coverageArea = coverageArea; }

    public Long getCoverageAmount() { return coverageAmount; }
    public void setCoverageAmount(Long coverageAmount) { this.coverageAmount = coverageAmount; }

    public Long getDailyRate() { return dailyRate; }
    public void setDailyRate(Long dailyRate) { this.dailyRate = dailyRate; }

    public String getCurrency() { return currency; }
    public void setCurrency(String currency) { this.currency = currency; }

    public Integer getMinAge() { return minAge; }
    public void setMinAge(Integer minAge) { this.minAge = minAge; }

    public Integer getMaxAge() { return maxAge; }
    public void setMaxAge(Integer maxAge) { this.maxAge = maxAge; }

    public String getOptions() { return options; }
    public void setOptions(String options) { this.options = options; }

    public Boolean getActive() { return active; }
    public void setActive(Boolean active) { this.active = active; }
}