package ru.ttravel.suppliers.airline.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;

/**
 * A purchasable offer: a {@link Flight} sold in a given fare class.
 * <p>
 * One flight has several fares (e.g. economy and business), each with its own
 * price and its own seat counter. The pair {@code flight} + {@code fareClass}
 * is unique and is what the public {@code offer_id} points to.
 * <p>
 * The seat counter is decreased when a booking is made and increased when it
 * is cancelled. It must never become negative: when it reaches zero, booking
 * is rejected with {@code NO_AVAILABILITY}.
 */
@Entity
@Table(name = "flight_fare",
    uniqueConstraints = @UniqueConstraint(columnNames = {"flight_id", "fare_class"}))
public class FlightFare {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "flight_id", referencedColumnName = "id", nullable = false)
    private Flight flight;

    /** Fare class code, e.g. {@code ECONOMY} or {@code BUSINESS}. Unique within a flight. */
    @Column(name = "fare_class", length = 16, nullable = false)
    private String fareClass;

    @Column(name = "price", nullable = false)
    private Long price;

    /** Number of seats still available in this fare class. Never negative. */
    @Column(name = "seats_available", nullable = false)
    private Integer seatsAvailable;

    /** Empty constructor, required by Hibernate. */
    protected FlightFare() {
    }

    /**
     * Creates a new fare. The id is generated by the database.
     *
     * @param flight         flight this fare belongs to
     * @param fareClass      fare class code, unique within the flight
     * @param price          price as an integer amount
     * @param seatsAvailable initial number of free seats
     */
    public FlightFare(Flight flight, String fareClass, Long price, Integer seatsAvailable) {
        this.flight = flight;
        this.fareClass = fareClass;
        this.price = price;
        this.seatsAvailable = seatsAvailable;
    }

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public Flight getFlight() {
        return flight;
    }

    public void setFlight(Flight flight) {
        this.flight = flight;
    }

    public String getFareClass() {
        return fareClass;
    }

    public void setFareClass(String fareClass) {
        this.fareClass = fareClass;
    }

    public Long getPrice() {
        return price;
    }

    public void setPrice(Long price) {
        this.price = price;
    }

    public Integer getSeatsAvailable() {
        return seatsAvailable;
    }

    public void setSeatsAvailable(Integer seatsAvailable) {
        this.seatsAvailable = seatsAvailable;
    }

}