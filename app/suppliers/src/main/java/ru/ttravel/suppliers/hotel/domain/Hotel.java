package ru.ttravel.suppliers.hotel.domain;

import java.lang.annotation.Inherited;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;

/**
 * A hotel in the hotel simulator.
 * <p>
 * The hotel itself holds no prices or availability: those belong to its
 * {@link RoomType}s and are tracked per night in {@link RoomAvailability}.
 */
@Entity
@Table(name = "hotel")
public class Hotel {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id;

    @Column(name = "name", nullable = false)
    private String name;

    @Column(name = "city", nullable = false)
    private String city;

    @Column(name = "address", nullable = false)
    private String address;

    @Column(name = "stars", nullable = false)
    private Integer stars;

    /** {@code true} if the hotel is active. Closed hotels are not shown in search. */
    @Column(name = "status", nullable = false)
    private Boolean status;

    /** Latitude in degrees. Optional, used for maps and transfer distance. */
    @Column(name = "lat", nullable = true)
    private Double lat;

    /** Longitude in degrees. Optional, used for maps and transfer distance. */
    @Column(name = "lon", nullable = true)
    private Double lon;

    /** Empty constructor, required by Hibernate. */
    protected Hotel() {}

    /**
     * Creates a new hotel. The id is generated by the database.
     *
     * @param name    hotel name
     * @param city    city name
     * @param address street address
     * @param stars   hotel class, 1 to 5
     * @param status  {@code true} if the hotel is active
     * @param lat     latitude, may be {@code null}
     * @param lon     longitude, may be {@code null}
     */
    public Hotel(String name, String city, String address, Integer stars, 
        Boolean status, Double lat, Double lon) {
            this.name = name;
            this.city = city;
            this.address = address;
            this.stars = stars;
            this.status = status;
            this.lat = lat;
            this.lon = lon;
    }

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getCity() {
        return city;
    }

    public void setCity(String city) {
        this.city = city;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public Integer getStars() {
        return stars;
    }

    public void setStars(Integer stars) {
        this.stars = stars;
    }

    public Boolean getStatus() {
        return status;
    }

    public void setStatus(Boolean status) {
        this.status = status;
    }

    public Double getLat() {
        return lat;
    }

    public void setLat(Double lat) {
        this.lat = lat;
    }

    public Double getLon() {
        return lon;
    }

    public void setLon(Double lon) {
        this.lon = lon;
    }
}
