CREATE TABLE airport (
    code     VARCHAR(3)   PRIMARY KEY,
    city_id  INTEGER      NOT NULL,   -- id in the reference service, no foreign key
    name     VARCHAR(255) NOT NULL,
    timezone VARCHAR(255) NOT NULL
);

CREATE TABLE aircraft (
    code        VARCHAR(3)   PRIMARY KEY,
    model       VARCHAR(255) NOT NULL,
    seats_total INTEGER      NOT NULL CHECK (seats_total > 0)
);

CREATE TABLE flight (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_no           VARCHAR(6)   NOT NULL,
    departure_airport   VARCHAR(3)   NOT NULL REFERENCES airport(code),
    arrival_airport     VARCHAR(3)   NOT NULL REFERENCES airport(code),
    scheduled_departure TIMESTAMPTZ  NOT NULL,
    scheduled_arrival   TIMESTAMPTZ  NOT NULL,
    aircraft_code       VARCHAR(3)   NOT NULL REFERENCES aircraft(code),
    status              VARCHAR(32)  NOT NULL,
    CONSTRAINT uq_flight_no_departure UNIQUE (flight_no, scheduled_departure),
    CONSTRAINT ck_flight_times CHECK (scheduled_arrival > scheduled_departure),
    CONSTRAINT ck_flight_status CHECK (status IN ('SCHEDULED', 'CANCELLED'))
);

CREATE TABLE flight_fare (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id       BIGINT      NOT NULL REFERENCES flight(id),
    fare_class      VARCHAR(16) NOT NULL,
    price           BIGINT      NOT NULL CHECK (price >= 0),   -- kopecks
    seats_available INTEGER     NOT NULL,
    CONSTRAINT uq_fare_flight_class UNIQUE (flight_id, fare_class),
    CONSTRAINT ck_fare_seats_non_negative CHECK (seats_available >= 0)
);

CREATE TABLE booking (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fare_id      BIGINT       NOT NULL REFERENCES flight_fare(id),
    offer_id     VARCHAR(255) NOT NULL,
    request_id   VARCHAR(255) NOT NULL,
    status       VARCHAR(32)  NOT NULL,
    price        BIGINT       NOT NULL CHECK (price >= 0),     -- kopecks
    created_at   TIMESTAMPTZ  NOT NULL,
    cancelled_at TIMESTAMPTZ,
    CONSTRAINT uq_booking_request_id UNIQUE (request_id),
    CONSTRAINT ck_booking_status CHECK (status IN ('RESERVED', 'CONFIRMED', 'CANCELLED'))
);

CREATE TABLE ticket (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     BIGINT       NOT NULL REFERENCES booking(id),
    passenger_name VARCHAR(255) NOT NULL,
    seat_no        VARCHAR(255)
);

CREATE INDEX idx_airport_city        ON airport(city_id);
CREATE INDEX idx_flight_route_date   ON flight(departure_airport, arrival_airport, scheduled_departure);
CREATE INDEX idx_booking_fare        ON booking(fare_id);
CREATE INDEX idx_booking_status      ON booking(status);
CREATE INDEX idx_ticket_booking      ON ticket(booking_id);